export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getRelatedProducts(product: Product, count: number = 4): Product[] {
  return products
    .filter((p) => p.id !== product.id && (p.category === product.category || (product.isEV && p.isEV)))
    .slice(0, count);
}

export function getProductsByCategory(categorySlug: string): Product[] {
  if (categorySlug === 'all') return products;
  return products.filter((p) => p.category === categorySlug);
}

export function getGarageProducts(): Product[] {
  return products.filter((p) => !p.isEV && p.productType !== 'electric-vehicle');
}

export function getEVProducts(): Product[] {
  return products.filter((p) => p.isEV || p.productType === 'electric-vehicle');
}

export function getProductsByVehicleType(type: '2-wheeler' | '3-wheeler' | 'component' | 'accessory'): Product[] {
  return products.filter((p) => (p.isEV || p.productType === 'electric-vehicle') && p.vehicleType === type);
}

export function getFeaturedEVProducts(count: number = 4): Product[] {
  return getEVProducts()
    .filter((p) => p.featured)
    .slice(0, count);
}

